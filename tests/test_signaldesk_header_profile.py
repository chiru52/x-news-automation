    def test_auth_not_faked_and_exported(self):
        page=(ROOT/"dashboard/account.html").read_text()
        export=(ROOT/"newsbot/dashboard_export.py").read_text()
        self.assertIn('id="auth-form" hidden',page)
        self.assertIn('type="password"',page)
        self.assertIn('"account.html"',export)
        self.assertIn('"account.mjs"',export)
        self.assertIn('"auth-config.json"',export)
        config=(ROOT/"dashboard/auth-config.json").read_text()
        self.assertIn('"enabled":true',config)
        client=(ROOT/"dashboard/account.mjs").read_text()
        self.assertIn("signInWithPassword",client)
        self.assertIn("signUp",client)
        self.assertIn("resetPasswordForEmail",client)
        self.assertIn("updateUser",client)
        self.assertNotIn("service_role",config)
        self.assertIn('verifiedUser=false',client)
        self.assertIn('id="profile-form"',page)
        self.assertIn('id="account-password-form"',page)
        for field in ("account-current-password","account-new-password","account-confirm-password"):
            self.assertIn(f'id="{field}"',page)
        self.assertNotIn('id="preferences-form"',page)
        self.assertNotIn('id="profile-password-reset"',page)
        self.assertNotIn('id="preference-region"',page)
        self.assertIn("client.auth.updateUser({data:{display_name}})",client)
        self.assertIn("client.auth.updateUser({password,current_password})",client)
        self.assertIn('if(password!==confirmation)',client)
        self.assertIn('if(password.length<6)',client)
        self.assertIn('$("account-password-form").reset()',client)
        self.assertIn('minlength="6"',page)
        self.assertIn('id="auth-name"',page)
        self.assertIn('account-showcase',page)
        self.assertIn('display_name:$("auth-name").value.trim()',client)
        self.assertIn('event==="PASSWORD_RECOVERY"',client)
        self.assertIn('mode==="update-password" && !verifiedUser',client)
        self.assertIn('previousElementSibling.hidden=mode==="update-password"',client)
        self.assertIn('else {form.hidden=mode==="update-password";}',client)
        self.assertIn('if(error){message(error.message);return;}',client)
        self.assertIn('renderAccountUser(null);message("Signed out.")',client)
        self.assertIn('location.assign(dashboardUrl)',client)
        self.assertIn('Password updated successfully. Please sign in',client)
        self.assertIn('const signedOut=await client.auth.signOut()',client)
        self.assertIn('id="account-continue"',page)
        self.assertIn('if(!client || (mode==="update-password" && !verifiedUser))return;',client)
        self.assertNotIn('recoveryAuthorized',client)
        self.assertIn('Password updated successfully.',client)
